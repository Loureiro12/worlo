/// <reference types="node" />
/**
 * Writes the Supabase seeds from the prototype data:
 *   supabase/seeds/catalog.sql  read-only content (countries, cities, tours…)
 *   supabase/seeds/demo.sql     the demo world: Ana (ana@worlo.app), friends and
 *                               experts, with their data, invites, posts and chats
 *
 *   pnpm --filter @worlo/mobile db:seed:generate
 *
 * Both are idempotent: catalog rows are updated in place, demo rows are only
 * inserted once (a reviewer's changes survive a re-run).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { type Catalog, catalogEntries } from '../src/data/catalogSpec';
import * as mocks from '../src/mocks/data.generated';
import { DEMO_USER } from '../src/mocks/demo';
import { Ago, DEMO_USERS, demoWorld } from '../src/mocks/demoWorld';

const out = (name: string) =>
  fileURLToPath(new URL(`../../../supabase/seeds/${name}`, import.meta.url));

const HEADER = '-- Generated by apps/mobile/scripts/generate-seed.ts. Do not edit by hand.\n';

function literal(value: unknown): string {
  if (value === null || value === undefined) return 'null';
  if (value instanceof Ago) return `now() - interval '${value.minutes} minutes'`;
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  const quote = (s: string) => `'${s.replaceAll("'", "''")}'`;
  if (typeof value === 'string') return quote(value);
  return `${quote(JSON.stringify(value))}::jsonb`;
}

function insert(table: string, rows: Record<string, unknown>[], conflict: string): string {
  if (!rows.length) return '';
  const columns = Object.keys(rows[0] as object);
  const values = rows.map((r) => `  (${columns.map((c) => literal(r[c])).join(', ')})`);
  return `insert into public.${table} (${columns.join(', ')}) values\n${values.join(',\n')}\n${conflict};\n\n`;
}

// ── Catalog ────────────────────────────────────────────────────────────────

const catalog = catalogEntries(mocks as unknown as Catalog);
writeFileSync(
  out('catalog.sql'),
  `${HEADER}\n${insert(
    'catalog',
    catalog,
    'on conflict (id) do update set kind = excluded.kind, key = excluded.key, sort = excluded.sort, data = excluded.data, deleted_at = null',
  )}`,
);

// ── Demo world ─────────────────────────────────────────────────────────────

const world = demoWorld();
const { profiles = [], people = [], ...tables } = world;
const ids = (rows: { id: string }[]) => rows.map((r) => literal(r.id)).join(', ');

let demo = `${HEADER}
-- Every demo account logs in with the same password (testers, App Review):
${DEMO_USERS.map((u) => `--   ${u.email} (${u.name})`).join('\n')}
--   password: ${DEMO_USER.password}
`;

for (const user of DEMO_USERS) {
  const uid = literal(user.id);
  demo += `
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
) values (
  '00000000-0000-0000-0000-000000000000', ${uid}, 'authenticated', 'authenticated',
  ${literal(user.email)}, extensions.crypt(${literal(DEMO_USER.password)}, extensions.gen_salt('bf')), now(),
  '{"provider": "email", "providers": ["email"]}', ${literal({ name: user.name })}, now(), now(),
  '', '', '', ''
) on conflict (id) do nothing;
insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)
values (
  ${uid}, ${uid}, ${uid}, 'email',
  ${literal({ sub: user.id, email: user.email, email_verified: true })}, now(), now(), now()
) on conflict do nothing;
`;
}

demo += `
-- The sign-up trigger created empty profiles; fill them once.
`;
for (const profile of profiles) {
  demo += `update public.profiles set
${Object.entries(profile)
  .filter(([k]) => !['id', 'created_at', 'updated_at', 'deleted_at'].includes(k))
  .map(([k, v]) => `  ${k} = ${literal(v)}`)
  .join(',\n')}
where id = ${literal(profile.id)} and onboarded_at is null;
`;
}

// people rows come from profiles (trigger); the seed only adds the expert fields.
demo += `\n${insert(
  'people',
  people.map(({ id, expert_role, expert_area }) => ({ id, expert_role, expert_area })),
  'on conflict (id) do update set expert_role = excluded.expert_role, expert_area = excluded.expert_area',
)}`;

for (const [table, rows] of Object.entries(tables)) {
  demo += insert(
    table,
    rows.map(({ updated_at: _server, ...row }) => row),
    table === 'post_votes'
      ? 'on conflict (post_id, user_id) do nothing'
      : 'on conflict (id) do nothing',
  );
}

// Triggers also reacted to the seeded memberships/follows/expenses/comments
// (notifications, activity). The seed brings its own; drop the duplicates.
demo += `delete from public.notifications
  where user_id in (${DEMO_USERS.map((u) => literal(u.id)).join(', ')})
    and id not in (${ids(tables.notifications ?? [])});
delete from public.activities
  where user_id in (${DEMO_USERS.map((u) => literal(u.id)).join(', ')})
    and id not in (${ids(tables.activities ?? [])});
`;

writeFileSync(out('demo.sql'), demo);
console.log(
  `catalog: ${catalog.length} rows · demo: ${DEMO_USERS.length} accounts, ${Object.values(tables).flat().length} rows`,
);
